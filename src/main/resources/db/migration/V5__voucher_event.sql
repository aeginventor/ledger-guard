-- 전표 상태 이력. 누가 언제 어떤 상태로 바꿨는지 남긴다. 409로 끝난 승인은 롤백되므로 남지 않는다.
CREATE TABLE voucher_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    voucher_id   BIGINT       NOT NULL,
    event_type   VARCHAR(20)  NOT NULL,
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    actor        VARCHAR(100),
    reason       VARCHAR(500),
    occurred_at  TIMESTAMP    NOT NULL,
    CONSTRAINT pk_voucher_event PRIMARY KEY (id),
    CONSTRAINT fk_voucher_event_voucher FOREIGN KEY (voucher_id) REFERENCES voucher (id)
);

CREATE INDEX idx_voucher_event_voucher ON voucher_event (voucher_id);
