-- H2(MODE=PostgreSQL)와 PostgreSQL 양쪽에서 동작하는 표준 SQL만 사용한다.

CREATE TABLE account (
    code         VARCHAR(10)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    type         VARCHAR(20)  NOT NULL,
    normal_side  VARCHAR(10)  NOT NULL,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    vat_related  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_account PRIMARY KEY (code)
);

CREATE TABLE accounting_period (
    yyyymm     VARCHAR(6) NOT NULL,
    closed     BOOLEAN    NOT NULL DEFAULT FALSE,
    closed_at  TIMESTAMP,
    CONSTRAINT pk_accounting_period PRIMARY KEY (yyyymm)
);

CREATE TABLE voucher (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    voucher_date        DATE         NOT NULL,
    description         VARCHAR(500) NOT NULL,
    counterparty_name   VARCHAR(200),
    counterparty_biz_no VARCHAR(20),
    evidence_type       VARCHAR(20)  NOT NULL,
    vat_type            VARCHAR(20)  NOT NULL,
    supply_amount       BIGINT,
    status              VARCHAR(20)  NOT NULL,
    drafter             VARCHAR(20)  NOT NULL,
    validation_overall  VARCHAR(10)  NOT NULL,
    approver            VARCHAR(100),
    approval_reason     VARCHAR(500),
    created_at          TIMESTAMP    NOT NULL,
    approved_at         TIMESTAMP,
    CONSTRAINT pk_voucher PRIMARY KEY (id)
);

CREATE INDEX idx_voucher_date ON voucher (voucher_date);
CREATE INDEX idx_voucher_status ON voucher (status);

CREATE TABLE voucher_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    voucher_id    BIGINT       NOT NULL,
    line_no       INTEGER      NOT NULL,
    account_code  VARCHAR(10)  NOT NULL,
    side          VARCHAR(10)  NOT NULL,
    amount        BIGINT       NOT NULL,
    memo          VARCHAR(300),
    CONSTRAINT pk_voucher_line PRIMARY KEY (id),
    CONSTRAINT fk_voucher_line_voucher FOREIGN KEY (voucher_id) REFERENCES voucher (id)
);

CREATE INDEX idx_voucher_line_voucher ON voucher_line (voucher_id);

CREATE TABLE validation_finding (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    voucher_id  BIGINT       NOT NULL,
    rule_code   VARCHAR(10)  NOT NULL,
    severity    VARCHAR(10)  NOT NULL,
    message     VARCHAR(500) NOT NULL,
    basis       VARCHAR(300),
    CONSTRAINT pk_validation_finding PRIMARY KEY (id),
    CONSTRAINT fk_validation_finding_voucher FOREIGN KEY (voucher_id) REFERENCES voucher (id)
);

CREATE INDEX idx_validation_finding_voucher ON validation_finding (voucher_id);

CREATE TABLE ledger_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    voucher_id    BIGINT      NOT NULL,
    line_no       INTEGER     NOT NULL,
    account_code  VARCHAR(10) NOT NULL,
    side          VARCHAR(10) NOT NULL,
    amount        BIGINT      NOT NULL,
    entry_date    DATE        NOT NULL,
    posted_at     TIMESTAMP   NOT NULL,
    CONSTRAINT pk_ledger_entry PRIMARY KEY (id),
    CONSTRAINT fk_ledger_entry_voucher FOREIGN KEY (voucher_id) REFERENCES voucher (id),
    CONSTRAINT fk_ledger_entry_account FOREIGN KEY (account_code) REFERENCES account (code)
);

CREATE INDEX idx_ledger_entry_date ON ledger_entry (entry_date);
CREATE INDEX idx_ledger_entry_account ON ledger_entry (account_code);
